function swatches(reg) {
  return Object.keys(reg).filter((k) => !k.startsWith('_')).sort().map((slug) => {
    const a = reg[slug];
    const cell = (mode) => `<div class="sw" data-theme="${mode}" data-app="${slug}"><span class="chip"></span><b>${esc(a.name)}</b><code>${esc(slug)}</code><code>${a[mode].accent}</code><button class="o-btn o-btn--primary">Go</button></div>`;
    return cell('dark') + cell('light');
  }).join('\n');
}

