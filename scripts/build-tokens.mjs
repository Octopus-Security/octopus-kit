// Generates tokens/tokens.css, tokens/accents.css and docs/preview.html from tokens/tokens.json and
// tokens/accents.json. Run after editing either; a test fails if the committed CSS drifts.
//   node scripts/build-tokens.mjs           write the files
//   node scripts/build-tokens.mjs --check   exit 1 if the committed files are stale
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));

const HEADER = '/* GENERATED by scripts/build-tokens.mjs from tokens/*.json. Do not edit by hand. */\n';
const decl = (obj, indent = '  ') =>
  Object.entries(obj).map(([k, v]) => `${indent}--o-${k}: ${v};`).join('\n');

// Selector for "no explicit dark/light choice": unset, "system" or anything unrecognised.
const AUTO = ':root:not([data-theme="dark"]):not([data-theme="light"])';

export function buildTokensCss(t) {
  const out = [HEADER];
  out.push(`:root,\n[data-theme="dark"] {\n  color-scheme: dark;\n${decl(t.dark)}\n${decl(t.shared)}\n}\n`);
  out.push(`@media (prefers-color-scheme: light) {\n  ${AUTO} {\n    color-scheme: light;\n${decl(t.light, '    ')}\n  }\n}\n`);
  out.push(`[data-theme="light"] {\n  color-scheme: light;\n${decl(t.light)}\n}\n`);
  out.push(`[data-density="compact"] {\n${decl(t.compact)}\n}\n`);
  return out.join('\n');
}

export function buildAccentsCss(reg) {
  const slugs = Object.keys(reg).filter((k) => !k.startsWith('_')).sort();
  const vars = (v) =>
    `--o-accent: ${v.accent}; --o-accent-hover: ${v.hover}; --o-accent-ink: ${v.ink};`;
  const dark = [], auto = [], light = [];
  for (const s of slugs) {
    const a = reg[s];
    dark.push(`[data-app="${s}"] { ${vars(a.dark)} } /* ${a.name} */`);
    auto.push(`  ${AUTO}[data-app="${s}"] { ${vars(a.light)} }`);
    light.push(`[data-theme="light"][data-app="${s}"] { ${vars(a.light)} }`);
  }
  return [
    HEADER,
    '/* Per-app accent. Set data-app="<slug>" on <html>. Link AFTER tokens.css (ties are won by order). A scoped region sets data-app and data-theme on the same element. */',
    dark.join('\n'),
    '',
    `@media (prefers-color-scheme: light) {\n${auto.join('\n')}\n}`,
    '',
    light.join('\n'),
    '',
  ].join('\n');
}

