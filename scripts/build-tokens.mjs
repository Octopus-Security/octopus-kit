export function generate() {
  const accents = read('tokens/accents.json');
  return {
    'tokens/tokens.css': buildTokensCss(read('tokens/tokens.json')),
    'tokens/accents.css': buildAccentsCss(accents),
    'docs/preview.html': buildPreviewHtml(accents),
  };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = generate();
  const check = process.argv.includes('--check');
  let stale = false;
  for (const [p, body] of Object.entries(files)) {
    const full = join(root, p);
    if (check) {
      let cur = '';
      try { cur = readFileSync(full, 'utf8'); } catch { /* missing */ }
      if (cur !== body) { console.error('stale: ' + p); stale = true; }
    } else {
      writeFileSync(full, body);
      console.log('wrote ' + p);
    }
  }
  if (check) { if (stale) process.exit(1); console.log('tokens up to date'); }
}
